const issueState = (issue) => {
  const f = issue?.fields ?? {};
  return [
    `${issue?.key ?? ''} [${f.issuetype?.name ?? '—'}, приоритет ${f.priority?.name ?? '—'}]`,
    f.summary ?? '',
    f.description ?? '',
  ].join('\n\n');
};

// Уровень сложности задачи Jira. null — классификатор выключен или упал: выбор агента прежний.
// Не уверен — tiers.uncertain: недооценить задачу дороже, чем переоценить.
export async function pickTier(issue, cfg, impl = classify) {
  if (!cfg?.tiers || cfg.tiers.enabled === false) return null;
  const res = await impl({
    role: 'task-tier',
    state: issueState(issue),
    cfg,
    questions: {
      tier: {
        instructions: 'Оцени сложность задачи Jira для агента, который её реализует в кодовой базе фронтенда.',
        criteria: cfg.tiers.criteria ?? TIER_CRITERIA,
      },
    },
  });
  if (!res) return null;
  return res.tier?.choice ?? cfg.tiers.uncertain ?? 'medium';
}

// Агенты уровня: slot 'plan' — планировщик и читающие действия, 'exec' — исполнитель.
export const tierAgents = (tier, cfg) => cfg?.tiers?.map?.[tier] ?? null;
